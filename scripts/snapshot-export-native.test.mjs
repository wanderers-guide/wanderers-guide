/** Execute real PG17 exports, PG16 sanitization and PG15-compatible restores on isolated CI services. */
import assert from "node:assert/strict";
import { execFileSync, spawnSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { after, before, test } from "node:test";
const root = fileURLToPath(new URL("../", import.meta.url));
const directory = mkdtempSync(join(tmpdir(), "wg-snapshot-export-"));
const targets = {
  source: "postgresql://postgres@127.0.0.1:55417/fixture_source",
  scratch: "postgresql://postgres@127.0.0.1:55416/fixture_scratch",
  compat: "postgresql://postgres@127.0.0.1:55415/fixture_compat",
};
const children = [
  "ability_block",
  "ancestry",
  "archetype",
  "background",
  "class",
  "creature",
  "item",
  "language",
  "spell",
  "trait",
  "versatile_heritage",
  "class_archetype",
];
const privateTables = [
  "public_user",
  "campaign",
  "character",
  "encounter",
  "content_update",
  "campaign_join_grant",
  "edge_work_budget",
];
const quote = (value) => '"' + value.replaceAll('"', '""') + '"';
const query = (target, sql) =>
  execFileSync(
    "psql",
    ["-X", "-qAt", "-v", "ON_ERROR_STOP=1", "-d", targets[target]],
    { input: sql, encoding: "utf8", stdio: ["pipe", "pipe", "pipe"] },
  ).trim();
const script = (name, args = []) =>
  spawnSync("bash", [resolve(root, "data", name), ...args], {
    cwd: directory,
    encoding: "utf8",
    timeout: 120000,
    maxBuffer: 2 * 1024 ** 2,
  });
const success = (result) => {
  assert.equal(result.error, undefined);
  assert.equal(result.signal, null);
  assert.equal(result.status, 0, result.stderr);
};
const failure = (result) => {
  assert.equal(result.error, undefined);
  assert.equal(result.signal, null);
  assert.equal(result.status, 3, result.stderr);
};
const official = (target) =>
  Object.fromEntries(
    ["content_source", ...children].map((table) => [
      table,
      JSON.parse(
        query(
          target,
          `select coalesce(jsonb_agg(to_jsonb(t) order by id),'[]') from public.${quote(table)} t where id=1;`,
        ),
      ),
    ]),
  );
let raw, expected, schema;
before(() => {
  assert.equal(
    process.env.GITHUB_ACTIONS,
    "true",
    "This destructive fixture test runs only on the isolated hosted services.",
  );
  for (const [name, major] of [
    ["source", 17],
    ["scratch", 16],
    ["compat", 15],
  ])
    assert.equal(
      Math.trunc(Number(query(name, "show server_version_num")) / 10000),
      major,
    );
  assert.match(
    execFileSync("pg_dump", ["--version"], { encoding: "utf8" }),
    /PostgreSQL\) 17\./,
  );
  query(
    "source",
    `create schema auth; create table auth.users(id uuid primary key); insert into auth.users values('00000000-0000-4000-8000-000000000001');
    create function auth.uid() returns uuid language sql stable as $$select null::uuid$$;
    create role fixture_reader nologin;
    create table public.content_source(id bigint generated by default as identity primary key,user_id uuid references auth.users(id),name text,contact_info text);
    insert into public.content_source(id,user_id,name,contact_info) values(1,null,'Official','public fixture'),(2,'00000000-0000-4000-8000-000000000001','Homebrew','private-source-sentinel');
    ${children.map((table) => `create table public.${quote(table)}(id bigint generated by default as identity primary key,content_source_id bigint references public.content_source(id) on delete cascade,payload text);insert into public.${quote(table)}(id,content_source_id,payload) values(1,1,'official-${table}'),(2,2,'private-homebrew-sentinel-${table}');`).join("\n")}
    ${privateTables.map((table) => `create table public.${quote(table)}(id bigint primary key,payload text);insert into public.${quote(table)} values(1,'excluded-private-table-sentinel');`).join("\n")}
    create function public.fixture_trigger() returns trigger language plpgsql as $$begin return new;end$$;
    create trigger fixture_write before insert on public.ability_block for each row execute function public.fixture_trigger();
    alter table public.ability_block enable row level security;
    create policy fixture_policy on public.ability_block using(auth.uid() is not null);
    grant select on public.ability_block to fixture_reader;
  `,
  );
  expected = official("source");
  success(script("ci-dump.sh", [targets.source]));
  raw = readFileSync(join(directory, "data.sql"), "utf8");
  schema = readFileSync(join(directory, "schema.sql"), "utf8");
});
after(() => rmSync(directory, { recursive: true, force: true }));

test("PG17 export keeps the complete schema while excluding private tables from data", () => {
  assert.match(
    raw,
    /private-homebrew-sentinel/,
    "prove that the later sanitizer really has private content to remove",
  );
  assert.doesNotMatch(raw, /excluded-private-table-sentinel/);
  assert.match(schema, /REFERENCES auth\.users/);
  assert.match(schema, /CREATE POLICY fixture_policy/);
  assert.match(schema, /CREATE TRIGGER fixture_write/);
  assert.match(schema, /GRANT SELECT.*fixture_reader/);
  assert.doesNotMatch(schema, /^SET transaction_timeout = 0;/m);
  const pre = readFileSync(
    join(directory, ".scratch/schema-pre-data.sql"),
    "utf8",
  );
  assert.doesNotMatch(
    pre,
    /REFERENCES auth\.users|CREATE POLICY|CREATE TRIGGER|GRANT SELECT/,
  );
});

test("strict scratch restore and sanitization preserve every official row without requiring Auth or cascades", () => {
  const restored = script("create-db.sh", [
    targets.scratch,
    ".scratch/schema-pre-data.sql",
  ]);
  success(restored);
  assert.doesNotMatch(
    restored.stdout + restored.stderr,
    /private-homebrew-sentinel|private-source-sentinel|excluded-private-table-sentinel/,
  );
  assert.equal(
    query("scratch", "select to_regclass('auth.users') is null"),
    "t",
  );
  assert.equal(
    query(
      "scratch",
      "select count(*) from pg_constraint where contype='f' and connamespace='public'::regnamespace",
    ),
    "0",
  );
  for (const table of children)
    assert.equal(
      query("scratch", `select count(*) from public.${quote(table)}`),
      "2",
    );
  success(script("clear-user-data.sh", [targets.scratch]));
  assert.deepEqual(official("scratch"), expected);
  for (const table of children)
    assert.equal(
      query("scratch", `select count(*) from public.${quote(table)}`),
      "1",
    );
  for (const table of privateTables)
    assert.equal(
      query("scratch", `select count(*) from public.${quote(table)}`),
      "0",
    );
});

test("the sanitized PG17-format output restores correctly on PostgreSQL15", () => {
  const dependencies = readFileSync(
    join(directory, ".scratch/schema-public-constraints.sql"),
    "utf8",
  );
  assert.doesNotMatch(dependencies, /REFERENCES auth\./);
  query("scratch", "BEGIN;" + dependencies + "COMMIT;");
  assert.equal(
    query(
      "scratch",
      "select count(*) from pg_constraint where contype='f' and connamespace='public'::regnamespace",
    ),
    String(children.length),
  );
  const dumped = execFileSync(
    "pg_dump",
    ["--data-only", "--table=public.*", targets.scratch],
    { encoding: "utf8" },
  );
  const filtered = spawnSync(
    "bash",
    [resolve(root, "data/filter-pg-dump.sh"), "portable"],
    { input: dumped, encoding: "utf8" },
  );
  success(filtered);
  assert.doesNotMatch(
    filtered.stdout,
    /private-homebrew-sentinel|private-source-sentinel|excluded-private-table-sentinel/,
  );
  writeFileSync(join(directory, "data.sql"), filtered.stdout);
  success(
    script("create-db.sh", [targets.compat, ".scratch/schema-pre-data.sql"]),
  );
  assert.deepEqual(official("compat"), expected);
  assert.equal(
    readFileSync(join(directory, "schema.sql"), "utf8"),
    schema,
    "scratch choices must not weaken the full artifact",
  );
});

test("the default one-argument initializer restores the full artifact on a prepared Supabase-compatible target", () => {
  query(
    "compat",
    "create schema auth; create table auth.users(id uuid primary key); create function auth.uid() returns uuid language sql stable as $$select null::uuid$$; create role fixture_reader nologin;",
  );
  success(script("create-db.sh", [targets.compat]));
  assert.deepEqual(official("compat"), expected);
  assert.equal(
    query(
      "compat",
      "select count(*) from pg_policy where polname='fixture_policy'",
    ),
    "1",
  );
  assert.equal(readFileSync(join(directory, "schema.sql"), "utf8"), schema);
});

test("malformed schema or COPY aborts restore without echoing private values", () => {
  writeFileSync(join(directory, "bad-schema.sql"), "not valid SQL;");
  failure(script("create-db.sh", [targets.scratch, "bad-schema.sql"]));
  const invalid = raw.replace(
    /^1\t\\N\tOfficial/m,
    "private-invalid-number\t\\N\tOfficial",
  );
  assert.notEqual(invalid, raw);
  writeFileSync(join(directory, "data.sql"), invalid);
  const result = script("create-db.sh", [
    targets.scratch,
    ".scratch/schema-pre-data.sql",
  ]);
  failure(result);
  assert.doesNotMatch(
    result.stdout + result.stderr,
    /private-invalid-number|private-homebrew-sentinel|private-source-sentinel/,
  );
});

test("private table rows or orphaned homebrew reject sanitization and roll back every deletion", () => {
  writeFileSync(join(directory, "data.sql"), raw);
  success(
    script("create-db.sh", [targets.scratch, ".scratch/schema-pre-data.sql"]),
  );
  query(
    "scratch",
    "insert into public.public_user values(99,'private-user-sentinel')",
  );
  failure(script("clear-user-data.sh", [targets.scratch]));
  assert.equal(
    query("scratch", "select count(*) from public.content_source"),
    "2",
  );
  for (const table of children)
    assert.equal(
      query("scratch", `select count(*) from public.${quote(table)}`),
      "2",
    );
  query(
    "scratch",
    "delete from public.public_user;insert into public.ability_block(id,content_source_id,payload) values(99,999,'orphan-private-sentinel')",
  );
  failure(script("clear-user-data.sh", [targets.scratch]));
  assert.equal(
    query("scratch", "select count(*) from public.content_source"),
    "2",
  );
  assert.equal(
    query("scratch", "select count(*) from public.ability_block"),
    "3",
  );
});
